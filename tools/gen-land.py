#!/usr/bin/env python3
"""Rasterize Natural Earth land polygons (public domain) into the land mask
used by the map: one bit per 0.5° cell, rows from 90°N southwards, columns
from 180°W eastwards, most significant bit first.

    curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_land.geojson
    python3 tools/gen-land.py ne_50m_land.geojson

Writes src/tui/land.bin (for the terminal) and plugin/Land.js (for the shell).
"""
import base64
import json
import sys
from pathlib import Path

STEP = 0.5
COLS, ROWS = int(360 / STEP), int(180 / STEP)


def rings(geojson):
    for f in geojson["features"]:
        g = f["geometry"]
        polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        for poly in polys:
            yield from poly  # outer ring and holes: even-odd fill handles both


def main(src):
    edges = []
    for ring in rings(json.load(open(src))):
        for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]):
            if y1 != y2:
                edges.append((x1, y1, x2, y2))
    bits = bytearray(COLS * ROWS // 8)
    for row in range(ROWS):
        lat = 90 - (row + 0.5) * STEP
        xs = []
        for x1, y1, x2, y2 in edges:
            if (y1 <= lat < y2) or (y2 <= lat < y1):
                xs.append(x1 + (lat - y1) * (x2 - x1) / (y2 - y1))
        xs.sort()
        for a, b in zip(xs[0::2], xs[1::2]):
            c0 = max(0, int((a + 180) / STEP + 0.5))
            c1 = min(COLS, int((b + 180) / STEP + 0.5))
            for col in range(c0, c1):
                i = row * COLS + col
                bits[i >> 3] |= 0x80 >> (i & 7)
    root = Path(__file__).resolve().parent.parent
    (root / "src/tui/land.bin").write_bytes(bits)
    b64 = base64.b64encode(bits).decode()
    lines = [b64[i : i + 100] for i in range(0, len(b64), 100)]
    js = (
        ".pragma library\n"
        "// Generated by tools/gen-land.py from Natural Earth (public domain).\n"
        f"// One bit per {STEP}° cell: {ROWS} rows from 90°N, {COLS} columns from 180°W.\n"
        f"var step = {STEP}\nvar cols = {COLS}\nvar rows = {ROWS}\n"
        "var data = \"\" +\n" + " +\n".join(f'    "{l}"' for l in lines) + "\n"
    )
    (root / "plugin/Land.js").write_text(js)
    land = sum(bin(b).count("1") for b in bits)
    print(f"{land} of {COLS * ROWS} cells are land ({100 * land / (COLS * ROWS):.1f}%)")
    # A coarse preview, so a broken mask is obvious.
    for row in range(0, ROWS, 12):
        print("".join(
            "#" if bits[(row * COLS + col) >> 3] & (0x80 >> ((row * COLS + col) & 7)) else "."
            for col in range(0, COLS, 6)))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "ne_50m_land.geojson")
